"""Regenerate static/css/pygments.css (code-highlight colours for both themes)."""
from pathlib import Path

from pygments.formatters import HtmlFormatter

OUTPUT = Path(__file__).resolve().parent.parent / "static" / "css" / "pygments.css"
THEMES = {"dark": "github-dark", "light": "default"}

parts = ["/* Generated by scripts/generate_pygments_css.py. Do not edit by hand. */"]
for theme, style in THEMES.items():
    scope = f'[data-theme="{theme}"] .codehilite'
    parts.append(HtmlFormatter(style=style).get_style_defs(scope))

OUTPUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
print(f"Wrote {OUTPUT}")
